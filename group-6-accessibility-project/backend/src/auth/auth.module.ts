import { Module } from '@nestjs/common';
import { JwtModule } from '@nestjs/jwt';
import { PassportModule } from '@nestjs/passport';
import { AuthService } from './auth.service';
import { AuthController } from './auth.controller';
import { DatabaseModule } from '../database/database.module';
import { UserAccessibilitySettingsModule } from '../user-accessibility-settings/user-accessibility-settings.module';

@Module({
  imports: [
    DatabaseModule, // Import database module for Prisma access
    UserAccessibilitySettingsModule, // Import for creating default accessibility settings
    PassportModule,
    JwtModule.register({
      secret: process.env.JWT_SECRET,
      signOptions: { expiresIn: '24h' },
    }),
  ],
  providers: [AuthService],
  controllers: [AuthController],
  exports: [AuthService],
})
export class AuthModule {}
